    <article id="article-2">
      <div class="article-header text-align-center" style="padding-bottom: var(--proportional-small-padding);">Особенности обучения в ФМШ</div>
      <div class="article-body-holder" id="fmsh-features-article">
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border" tabindex="0" role="button" name="Открыть выпадающий текст">
              <h3 class="text-dropdown-title">Глубокое изучение материала</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
          В основе обучения в ФМШ лежит принцип глубокого понимания изучаемого материала. Мы делаем акцент не на количестве или сложности решаемых задач, а на осознанном применении знаний и понимании их взаимосвязей. Особое внимание уделяется критическому мышлению: учащиеся учатся понимать не только сами формулы и методы, но и границы их применимости.
          <br>
          <br>
          Мы поощряем любые вопросы по изучаемому материалу и ни в коем случае не осуждаем за ошибки, поскольку именно вопросы и ошибки приводят к наилучшему пониманию материала. Наши занятия часто продолжаются дольше запланированного времени, ведь мы работаем "до последнего вопроса", заданного учениками.
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border" tabindex="0" role="button" name="Открыть выпадающий текст">
              <h3 class="text-dropdown-title">Оценки и обратная связь</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
          В ФМШ большинство преподавателей не используют традиционную балльную систему оценивания, делая основной акцент на понимании материала и умении его применять. Вместо сухих формальных оценок преподаватели дают комментарии по работам и вовлекают учащихся в дискуссии.
          <br>
          <br>
          В процессе обучения ошибки не воспринимаются как что-то негативное – наоборот, они помогают лучше разобраться в материале. Когда ученик ошибается, это позволяет увидеть, какие моменты требуют дополнительного внимания и проработки. Благодаря такому подходу учащиеся не боятся задавать вопросы и высказывать свои идеи, даже если не уверены в их правильности.
          <br>
          <br>
          На семинарах учащиеся активно обсуждают работы друг друга, задают вопросы и делятся конструктивными замечаниями. Такие обсуждения помогают глубже разобраться в материале, учат корректно формулировать свои мысли и развивают умение вести научную дискуссию.
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border" tabindex="0" role="button" name="Открыть выпадающий текст">
              <h3 class="text-dropdown-title">Гибкая программа обучения</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
            В ФМШ не используются фиксированные программы. Новые занятия преподаватели планируют в зависимости от того, как прошли предыдущие занятия, какие задавали вопросы и делали комментарии учащиеся в их процессе: если материал оказался слишком простым – усложняют, оптимальным – продолжают двигаться в том же направлении, слишком сложным – упрощают либо переключаются на совершенно другой материал.
            <br>
            <br>
            При возникновении ситуаций, когда одна часть учащихся быстро разобралась в изучаемом материале, а другой части данный материал даётся трудно, преподаватель может либо уделить несколько большее время тем, у кого возникли сложности (при этом предложив другой части аудитории возможность подумать над более сложными вопросами по рассматриваемой теме), либо перейти к новому материалу, если глубокое понимание текущей темы на данный момент не является необходимым.
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border" tabindex="0" role="button" name="Открыть выпадающий текст">
              <h3 class="text-dropdown-title">Преподаватели показывают науку «в действии»</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
          Преподаватели показывают науку "в действии": объясняют, как развиваются научные теории, какие проблемы они решают, и какие вопросы еще предстоит исследовать. Благодаря такому подходу у учащихся формируется целостное представление о науке как о системе взаимосвязанных знаний. Обучение проходит в формате семинаров, где помимо основного материала уделяется время обсуждению смежных научных тем, интересующих учащихся.
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border" tabindex="0" role="button" name="Открыть выпадающий текст">
              <h3 class="text-dropdown-title">Вовлеченность учащихся в образовательный процесс</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
            Старшие учащиеся ФМШ могут проводить семинары и помогать в проведении вступительных испытаний. Это не только помогает новым ученикам быстрее адаптироваться, но и позволяет старшим учащимся лучше понять принципы преподавания и углубить собственные знания.
          </div>  
        </div>
