    <article id="article-2">
      <div class="article-header text-align-center" style="padding-bottom: var(--proportional-small-padding);">Особенности обучения в ФМШ</div>
      <div class="article-body-holder" id="fmsh-features-article">
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border">
              <h3 class="text-dropdown-title">В ФМШ поступают действительно заинтересованные в глубоком изучении материала студенты</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
            В случае проведения письменного экзамена или обучающих семинаров основное внимание обращается не на формальное умение решать те или иные задачи, а на осознанное применение имеющихся знаний.
            <br>
            <br>
            Творческий конкурс по математике – это возможность для поступающих продемонстрировать свои интересы в области математики и одновременно активно обсуждать их в рамках предварительных семинаров как с преподавателями ФМШ, так и с другими поступающими.
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border">
              <h3 class="text-dropdown-title">Преподаватели подстраивают программу обучения по результатам и по вопросам студентов</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
            В ФМШ не используются фиксированные программы: новые занятия преподаватели планируют в зависимости от того, как прошли предыдущие занятия, какие задавали вопросы и делали комментарии учащиеся в их процессе: если материал оказался слишком простым – усложняют, оптимальным – продолжают двигаться в том же направлении, слишком сложным – упрощают либо переключаются на совершенно другой материал.
            <br>
            <br>
            При возникновении ситуаций, когда одна часть учащихся быстро разобралась в изучаемом материале, а другой части данный материал даётся трудно, преподаватель может либо уделить несколько большее время тем, у кого возникли сложности (при этом предложив другой части аудитории возможность подумать над более сложными вопросами по рассматриваемой теме), либо перейти к новому материалу, если глубокое понимание текущей темы на данный момент не является необходимым.
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border">
              <h3 class="text-dropdown-title">Многие преподаватели уделяют время расширению кругозора учащихся</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
          Обучение в ФМШ осуществляется в форме семинаров, на которых многие преподаватели выделяют отдельное время для общения на темы, лишь косвенно связанные с основным материалом, но представляющие интерес для конкретных учащихся.
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border">
              <h3 class="text-dropdown-title">В ФМШ особое внимание уделяется осознанию материала</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
            В процессе обучения в ФМШ особое внимание уделяется не количеству или сложности материала, а его осознанию; преподаватели стимулируют учащихся задавать любые вопросы по изучаемому материалу.
            <br>
            <br>
            В результате учащиеся начинают понимать, что формальные знания без учёта ограничений их применения зачастую приводят к неверным результатам, и стремятся не только выяснять все детали изучаемого материала, но и находить его связь с материалом, изученным ранее; занятия ФМШ зачастую продолжаются и после формального времени окончания, т.к. мы традиционно работаем «до последнего вопроса».
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border">
              <h3 class="text-dropdown-title">Преподаватели показывают науку «в действии»</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
            Преподаватели стараются показывать изучаемые предметы «в действии», то есть как и почему строится наука, какие проблемы и как она решает, на какие вопросы отвечает, на какие ответит со временем, а какие вообще не имеют к ней отношения. Благодаря этому у учащихся создаётся целостное представление о науке как о системе взаимосвязанных знаний.
          </div>  
        </div>
        <div class="text-dropdown-container">
          <div class="text-dropdown-header has-border">
              <h3 class="text-dropdown-title">Учащиеся ФМШ участвуют в различных форматах работы наравне с преподавателями</h3>
              <div class="text-dropdown-arrow"></div>
          </div>
          <div class="text-dropdown-content">
            Учащиеся ФМШ проводят семинары для поступающих и оценивают их работу на вступительных испытаниях. Это помогает учащимся лучше понимать взаимодействие между участниками учебного процесса и помогает новым поступающим быстрее адаптироваться.
          </div>  
        </div>
      </div>
